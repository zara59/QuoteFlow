/* ============================================================
   QuoteFlow API — seed data
   Usage:
     node src/db/seed.js           seed only when the tables are empty
     node src/db/seed.js --reset   wipe first, then seed

   Ids are generated by PostgreSQL. Quotes and bookings reference
   customers by name at insert time, so nothing depends on the old
   Stage 3 in-memory ids.

   OWNERSHIP (Stage 5)
   Two development users are created and the sample data is split
   between them, so a signed-in user sees a genuinely partial view
   rather than the whole dataset. A quote or booking always inherits
   the owner of its customer, which keeps the ownership columns
   internally consistent.
   ============================================================ */

