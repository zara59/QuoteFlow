const seed = async () => {
  const userIds = await ensureSeedUsers()

  await withTransaction(async (client) => {
    const idByName = {}

    for (const customer of CUSTOMERS) {
      const userId = USER_A_CUSTOMERS.has(customer.name) ? userIds.a : userIds.b
      const { rows: created } = await client.query(
        `INSERT INTO customers (user_id, name, email, phone, company, location, created_at)
         VALUES ($1, $2, NULLIF($3, ''), NULLIF($4, ''), NULLIF($5, ''), NULLIF($6, ''), $7::timestamptz)
         RETURNING id`,
        [userId, customer.name, customer.email, customer.phone, customer.company, customer.location, `${customer.createdAt}T09:00:00Z`],
      )
      // Quotes and bookings copy the owner from here.
      idByName[customer.name] = { id: created[0].id, userId }
    }

    for (const quote of QUOTES) {
      const customer = idByName[quote.customer]
      if (!customer) throw new Error(`Seed quote references unknown customer "${quote.customer}".`)
      await client.query(
        `INSERT INTO quotes (user_id, customer_id, service, description, amount, valid_until, status, created_at)
         VALUES ($1, $2, $3, $4, $5, $6::date, $7, $8::timestamptz)`,
        [customer.userId, customer.id, quote.service, quote.description, quote.amount, quote.validUntil, quote.status, `${quote.createdAt}T09:00:00Z`],
      )
    }

    for (const booking of BOOKINGS) {
      const customer = idByName[booking.customer]
      if (!customer) throw new Error(`Seed booking references unknown customer "${booking.customer}".`)
      await client.query(
        `INSERT INTO bookings (user_id, customer_id, service, date, "time", duration, status, location, notes, created_at)
         VALUES ($1, $2, $3, $4::date, $5::time, NULLIF($6, ''), $7, NULLIF($8, ''), NULLIF($9, ''), $4::timestamptz)`,
        [customer.userId, customer.id, booking.service, booking.date, booking.time, booking.duration, booking.status, booking.location, booking.notes],
      )
    }
  })
}

const run = async () => {
  const reset = process.argv.includes('--reset')

  if (reset) {
    /* users first: they are referenced by every business row, so the
       cascade is what keeps the truncate atomic. */
    await query('TRUNCATE bookings, quotes, customers, users RESTART IDENTITY CASCADE')
    console.log('Cleared existing rows.')
  } else {
    const existing = await one('SELECT COUNT(*)::int AS count FROM customers')
    if (existing.count > 0) {
      console.log(`customers already has ${existing.count} row(s) — nothing to do. Use --reset to reseed.`)
      await closePool()
      process.exit(0)
    }
  }

  await seed()

  const [userCount, customerCount, quoteCount, bookingCount] = await Promise.all([
    one('SELECT COUNT(*)::int AS count FROM users'),
    one('SELECT COUNT(*)::int AS count FROM customers'),
    one('SELECT COUNT(*)::int AS count FROM quotes'),
    one('SELECT COUNT(*)::int AS count FROM bookings'),
  ])

  console.log(
    `Seeded ${userCount.count} users, ${customerCount.count} customers, ${quoteCount.count} quotes, ${bookingCount.count} bookings.`,
  )
  console.log(
    `  ${SEED_USERS.a.email} — ${USER_A_CUSTOMERS.size} customers\n` +
      `  ${SEED_USERS.b.email} — ${CUSTOMERS.length - USER_A_CUSTOMERS.size} customers\n` +
      `  (development password for both: ${SEED_USERS.a.password})`,
  )
}

run()
  .then(() => closePool())
  .then(() => process.exit(0))
  .catch(async (error) => {
    console.error('Seed failed:', error.message)
    await closePool().catch(() => {})
    process.exit(1)
  })
